// Fonts for the extension frames (식사 신청, 관리대장, every installed extension). The frames
// have their own origin and no network, so they cannot use the fonts bundled with the main
// screen: without this their text falls back to the browser's default serif face.
// Copies Pretendard (body, the font of the rest of the program) and Do Hyeon (large titles)
// into resources/fonts and writes fonts.css; src/main/plugins.ts serves both to every frame
// as __fonts.css and __font/<file>, and the SDK script links the stylesheet.
//   node scripts/build-fonts.mjs
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const out = join(root, 'resources', 'fonts')
rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })

const pretendard = join(root, 'node_modules', 'pretendard', 'dist', 'web', 'variable', 'woff2', 'PretendardVariable.woff2')
const doHyeon = join(root, 'node_modules', '@fontsource', 'do-hyeon')
if (!existsSync(pretendard) || !existsSync(join(doHyeon, '400.css'))) {
  console.error('fonts: font packages are missing (pnpm install)')
  process.exit(1)
}
copyFileSync(pretendard, join(out, 'PretendardVariable.woff2'))
let n = 1
for (const f of readdirSync(join(doHyeon, 'files'))) {
  if (!f.endsWith('-400-normal.woff2')) continue
  copyFileSync(join(doHyeon, 'files', f), join(out, f))
  n++
}
// the package's own @font-face list (one per unicode range), pointed at the served path, woff2 only
const faces = readFileSync(join(doHyeon, '400.css'), 'utf8')
  .replace(/src: url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\), url\([^)]+\) format\('woff'\);/g, "src: url(__font/$1) format('woff2');")
if (faces.includes('./files/')) {
  console.error('fonts: unexpected layout of @fontsource/do-hyeon/400.css')
  process.exit(1)
}
const css = `/* generated by scripts/build-fonts.mjs */
@font-face {
  font-family: 'Pretendard Variable';
  font-weight: 45 920;
  font-style: normal;
  font-display: swap;
  src: url(__font/PretendardVariable.woff2) format('woff2-variations');
}
/* the name extensions already ask for */
@font-face {
  font-family: 'Pretendard';
  font-weight: 45 920;
  font-style: normal;
  font-display: swap;
  src: url(__font/PretendardVariable.woff2) format('woff2-variations');
}
${faces}
/* body text: the same face as the rest of TeamHub */
html, body, button, input, select, textarea, table {
  font-family: 'Pretendard Variable', Pretendard, 'Malgun Gothic', '맑은 고딕', sans-serif;
}
/* large titles: a display face (it has one weight, so no synthetic bold) */
h1, h2, .th-title {
  font-family: 'Do Hyeon', 'Pretendard Variable', Pretendard, 'Malgun Gothic', sans-serif;
  font-weight: 400;
  letter-spacing: 0.01em;
}
`
writeFileSync(join(out, 'fonts.css'), css)
console.log(`fonts: ${n} files -> resources/fonts`)
